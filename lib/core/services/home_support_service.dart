import '../../providers/mood_provider.dart';

class HomeSupportService {
  HomeSupportService();

  static int _counter = -1;

  Future<String> loadSupportText({
    required String userName,
    MoodEntry? latestEntry,
  }) async {
    final mood = latestEntry?.emotion.toLowerCase() ?? '';
    final pool = <String>[
      if (mood.contains('anx')) ..._anxietyTips,
      if (mood.contains('sad')) ..._sadTips,
      if (mood.contains('calm')) ..._calmTips,
      if (mood.contains('happy')) ..._happyTips,
      ..._generalTips,
    ];

    _counter = (_counter + 1) % pool.length;
    return pool[_counter];
  }

  static const _generalTips = [
    'Сделай один маленький шаг для себя.',
    'Сегодня можно замедлиться.',
    'Ты уже молодец, что зашла сюда.',
    'Сейчас достаточно просто сделать паузу.',
    'Не нужно решать всё прямо сейчас.',
    'Попробуй заметить, что тебе сейчас нужно.',
    'Можно начать с пары спокойных вдохов.',
    'Выбери самое мягкое действие на 2 минуты.',
    'Пусть сегодня будет не идеально, а бережно.',
    'Иногда помогает просто налить воды.',
    'Сделай маленькую паузу без телефона.',
    'Проверь плечи, челюсть и дыхание.',
    'Можно двигаться очень медленно.',
    'Один короткий выдох уже считается заботой.',
    'Спроси себя: что сейчас облегчит момент?',
  ];

  static const _anxietyTips = [
    'Если тревожно — попробуй медленный выдох.',
    'Назови 3 предмета вокруг себя.',
    'Поставь стопы на пол и выдохни.',
    'Сейчас не нужно торопить себя.',
  ];

  static const _sadTips = [
    'Будь к себе мягче сегодня.',
    'Можно сделать день чуть проще.',
    'Сейчас достаточно одного тёплого действия.',
    'Позволь себе не быть продуктивной.',
  ];

  static const _calmTips = [
    'Хороший момент закрепить это состояние.',
    'Запомни, что сейчас помогает тебе.',
    'Можно поддержать этот спокойный ритм.',
  ];

  static const _happyTips = [
    'Пусть это чувство останется подольше.',
    'Заметь, что сегодня сработало хорошо.',
    'Можно сохранить этот момент в дневнике.',
  ];
}
